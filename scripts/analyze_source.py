#!/usr/bin/env python3
"""Analyze a Python backtrader strategy with AST; emit analysis.json + context.md.

Usage:
    python3 analyze_source.py <strategy.py> [--out-dir DIR]

Produces machine-readable facts (classes, methods, indicators, params, order calls,
data-line accesses) that the converting agent reads IN PLACE OF re-reading the whole
source. Never modifies the source file.
"""
import argparse
import ast
import json
import os
import sys


def _unparse(node):
    try:
        return ast.unparse(node)
    except Exception:
        return "<expr>"


class Visitor(ast.NodeVisitor):
    def __init__(self):
        self.classes = []
        self.params = []
        self.indicators = []
        self.order_calls = []
        self.data_access = []
        self.analyzers = []
        self.imports = []
        self._class = None

    def visit_Import(self, node):
        self.imports.extend(a.name for a in node.names)
        self.generic_visit(node)

    def visit_ImportFrom(self, node):
        self.imports.append(f"{node.module}:{','.join(a.name for a in node.names)}")
        self.generic_visit(node)

    def visit_ClassDef(self, node):
        bases = [_unparse(b) for b in node.bases]
        info = {"name": node.name, "bases": bases, "methods": []}
        prev = self._class
        self._class = info
        for child in node.body:
            if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef)):
                info["methods"].append({
                    "name": child.name,
                    "args": [a.arg for a in child.args.args],
                    "lineno": child.lineno,
                })
            if isinstance(child, ast.Assign) and any(
                    isinstance(t, ast.Name) and t.id == "params" for t in child.targets):
                try:
                    self.params = ast.literal_eval(child.value)
                    self.params = [list(x) for x in self.params] if isinstance(self.params, (tuple, list)) else []
                except Exception:
                    self.params = _unparse(child.value)
        self.classes.append(info)
        self.generic_visit(node)
        self._class = prev

    def visit_Call(self, node):
        fn = _unparse(node.func)
        low = fn.lower()
        if "indicator" in low or any(t in low for t in ("bollinger", "sma", "ema", "rsi", "macd", "atr")):
            self.indicators.append({"call": fn, "args": [_unparse(a) for a in node.args],
                                    "lineno": node.lineno})
        if low.endswith(".buy") or low.endswith(".sell") or low.endswith(".close") or fn in ("buy", "sell", "close"):
            self.order_calls.append({"call": fn, "kwargs": [k.arg for k in node.keywords],
                                     "lineno": node.lineno})
        if "analyzer" in low or any(t in low for t in ("sharpe", "returns", "drawdown", "tradeanalyzer")):
            self.analyzers.append({"call": fn, "lineno": node.lineno})
        if ".current_funding_rate" in fn or ".mark_price" in fn or "getdatabyname" in low:
            self.data_access.append({"expr": fn, "lineno": node.lineno})
        self.generic_visit(node)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("source", help="Python backtrader strategy file")
    ap.add_argument("--out-dir", default=None)
    a = ap.parse_args()
    src = os.path.abspath(a.source)
    out_dir = a.out_dir or os.path.dirname(src)
    os.makedirs(out_dir, exist_ok=True)

    with open(src, encoding="utf-8") as f:
        tree = ast.parse(f.read(), filename=src)
    v = Visitor()
    v.visit(tree)

    is_bt = any("backtrader" in str(i) for i in v.imports)
    facts = {
        "source": src,
        "imports_backtrader": is_bt,
        "strategy_classes": [c for c in v.classes if any("Strategy" in b for b in c["bases"])],
        "all_classes": v.classes,
        "params": v.params,
        "indicators": v.indicators,
        "order_calls": v.order_calls,
        "analyzers": v.analyzers,
        "custom_data_access": v.data_access,
        "imports": v.imports,
        "notes": [],
    }
    if not is_bt:
        facts["notes"].append("Source does not import backtrader — verify it is the right oracle.")
    if not facts["strategy_classes"]:
        facts["notes"].append("No bt.Strategy subclass found — conversion target unclear.")

    with open(os.path.join(out_dir, "analysis.json"), "w", encoding="utf-8") as f:
        json.dump(facts, f, indent=2, ensure_ascii=False)

    lines = ["# Source analysis (generated by bt2any)", "",
             f"- source: `{src}`", f"- backtrader import: {is_bt}",
             f"- strategy classes: {[c['name'] for c in facts['strategy_classes']]}", "",
             "## Params", ""]
    if isinstance(v.params, list):
        for p in v.params:
            lines.append(f"- {p}")
    else:
        lines.append(str(v.params))
    lines += ["", "## Indicators", ""]
    for i in v.indicators:
        lines.append(f"- L{i['lineno']}: {i['call']}({', '.join(i['args'])})")
    lines += ["", "## Order calls", ""]
    for o in v.order_calls:
        lines.append(f"- L{o['lineno']}: {o['call']} kwargs={o['kwargs']}")
    lines += ["", "## Analyzers", ""]
    for an in v.analyzers:
        lines.append(f"- L{an['lineno']}: {an['call']}")
    lines += ["", "## Custom data lines", ""]
    for d in v.data_access:
        lines.append(f"- L{d['lineno']}: {d['expr']}")
    if facts["notes"]:
        lines += ["", "## Notes", ""] + [f"- {n}" for n in facts["notes"]]
    with open(os.path.join(out_dir, "context.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

    print(f"Wrote {out_dir}/analysis.json and {out_dir}/context.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
